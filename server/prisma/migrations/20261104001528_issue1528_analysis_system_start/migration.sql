-- Issue #1528 — make `analyses.startedById` NULLABLE, so the system can start
-- an analysis.
--
-- A scheduled `rerun-analysis` task started its run with `startedById:
-- "system"`. No `users` row has that id and the column was a NOT NULL foreign
-- key to `users`, so `createAnalysis` failed the insert ("Foreign key
-- constraint violated") and a scheduled re-run never started. Reproduced on a
-- migrated SQLite (server/tests/scheduled-analysis-system-start-1528.sqlite.test.ts).
--
-- A system start is now stored as NULL: the orchestrator is still handed
-- `SYSTEM_ACTOR_ID` (audit rows keep their `actorType: "system"`, #1518) and
-- `createAnalysis` writes it as NULL. A seeded "system" user was rejected: SCIM
-- would list it to the identity provider and it would sit in every user list.
--
-- The foreign key keeps ON DELETE RESTRICT, so NULL never means a deleted user.
--
-- SQLite cannot relax a NOT NULL in place, so the table is rebuilt (Prisma's
-- RedefineTables, generated by `prisma migrate diff`). No existing row changes
-- value: the INSERT..SELECT copies every column verbatim.
--
-- Rollback (documentation): rebuild the table with "startedById" TEXT NOT NULL
-- after deleting or re-attributing every row whose "startedById" IS NULL.

-- RedefineTables
PRAGMA defer_foreign_keys=ON;
PRAGMA foreign_keys=OFF;
CREATE TABLE "new_analyses" (
    "id" TEXT NOT NULL PRIMARY KEY,
    "projectId" TEXT NOT NULL,
    "status" TEXT NOT NULL DEFAULT 'pending',
    "startedById" TEXT,
    "startedAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "completedAt" DATETIME,
    "inputTokens" INTEGER NOT NULL DEFAULT 0,
    "outputTokens" INTEGER NOT NULL DEFAULT 0,
    "totalTokens" INTEGER NOT NULL DEFAULT 0,
    "errorMessage" TEXT,
    "metadata" TEXT,
    "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" DATETIME NOT NULL,
    "deletedAt" DATETIME,
    CONSTRAINT "analyses_projectId_fkey" FOREIGN KEY ("projectId") REFERENCES "projects" ("id") ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "analyses_startedById_fkey" FOREIGN KEY ("startedById") REFERENCES "users" ("id") ON DELETE RESTRICT ON UPDATE CASCADE
);
