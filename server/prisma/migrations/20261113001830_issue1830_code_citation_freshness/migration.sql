-- Issue #1830 (epic #1827) — stamp each requirement→code citation with the
-- code-graph version it was read from, and whether it still holds.
--
--   codeGraphId        the graph of the repository the cited file belongs to
--                      (FK to code_graphs, ON DELETE SET NULL: a link outlives
--                      its graph and reads as not re-checkable).
--   commitSha          copied from that graph at write time.
--   freshness          fresh | moved | stale | unverified, DEFAULT 'unverified'.
--   validatedAt        when the freshness was last decided.
--   previousFilePath / previousStartLine / previousEndLine
--                      the location a `moved` citation was rewritten from.
--   staleReason        file-missing | symbol-missing | content-changed.
--
-- Every existing row reads `freshness = 'unverified'` (never `fresh`: nothing
-- has checked it), and null in every other new column. Nothing is backfilled.
--
-- SQLite cannot add a foreign-key column the way Prisma records one, so the
-- table is rebuilt (Prisma's RedefineTables, generated by `prisma migrate
-- diff`). The INSERT..SELECT copies every existing column verbatim.
--
-- Rollback: server/prisma/rollbacks/20261113001830_issue1830_code_citation_freshness.sql
-- (exercised by server/tests/code-citation-freshness-migration-1830.sqlite.test.ts).

-- RedefineTables
PRAGMA defer_foreign_keys=ON;
PRAGMA foreign_keys=OFF;
CREATE TABLE "new_requirement_code_mappings" (
    "id" TEXT NOT NULL PRIMARY KEY,
    "requirementId" TEXT NOT NULL,
    "projectId" TEXT NOT NULL,
    "codeSymbolId" TEXT,
    "filePath" TEXT NOT NULL,
    "startLine" INTEGER,
    "endLine" INTEGER,
    "confidence" REAL NOT NULL DEFAULT 0.7,
    "source" TEXT NOT NULL DEFAULT 'semantic',
    "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "codeGraphId" TEXT,
    "commitSha" TEXT,
    "freshness" TEXT NOT NULL DEFAULT 'unverified',
    "validatedAt" DATETIME,
    "previousFilePath" TEXT,
    "previousStartLine" INTEGER,
    "previousEndLine" INTEGER,
    "staleReason" TEXT,
    CONSTRAINT "requirement_code_mappings_requirementId_fkey" FOREIGN KEY ("requirementId") REFERENCES "requirements" ("id") ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "requirement_code_mappings_projectId_fkey" FOREIGN KEY ("projectId") REFERENCES "projects" ("id") ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT "requirement_code_mappings_codeSymbolId_fkey" FOREIGN KEY ("codeSymbolId") REFERENCES "code_symbols" ("id") ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT "requirement_code_mappings_codeGraphId_fkey" FOREIGN KEY ("codeGraphId") REFERENCES "code_graphs" ("id") ON DELETE SET NULL ON UPDATE CASCADE
);
