/**
 * Idempotency helpers — Phase 9 (#68).
 *
 * `dedupHash` is sha256(targetOwner + "/" + targetRepo + ":" + normalizedTitle).
 * The hash is stamped on the IssueDraft AND embedded in a marker comment in
 * the published issue body so the linkage can be recovered if the local
 * PublishedIssue row is lost.
 *
 * The marker is a single HTML comment line of the form:
 *
 *   <!-- metis-publish: batch=<batchId> draft=<draftId> hash=<dedupHash> -->
 *
 * Re-publishing with the same dedup hash returns the existing issue number
 * instead of creating a new one (idempotent batch).
 */
import crypto from "node:crypto";
import { PUBLISH_MARKER_PREFIX } from "@metis/shared";

/**
 * Marker recogniser. Always rebuild a fresh RegExp at use sites — never
 * reuse this instance with the global flag (state leaks between exec()
 * calls). For global stripping see `MARKER_RE_GLOBAL` below.
 */
const MARKER_RE = new RegExp(
  `${escapeRe(PUBLISH_MARKER_PREFIX)}\\s*batch=([^\\s]+)\\s+draft=([^\\s]+)\\s+hash=([^\\s]+)\\s*-->`,
  "i",
);

/**
 * #1064 — where a published issue came from: the METIS project, analysis and
 * requirement. These ids used to be printed in a visible footer
 * (`> Generated by METIS · project=… · analysis=… · requirement=…`); they now
 * ride a second HTML comment, written next to the publish marker when the issue
 * is published:
 *
 *   <!-- metis-source: project=<id> analysis=<id> requirement=<id> -->
 *
 * This is tidiness, not secrecy: an HTML comment is not rendered, but anyone
 * who can read the issue can read its source. Never put a secret in it.
 */
export const SOURCE_MARKER_PREFIX = "<!-- metis-source:";

/** A source-marker value: an opaque id. Anything else is left out of the marker. */
const SOURCE_ID_RE = /^[A-Za-z0-9_-]{1,64}$/;

/** One source marker. The body is bounded, so a flood of prefixes stays linear. */
const SOURCE_MARKER_BODY = "[ \\t]*metis-source:([^>\\n]{0,300})-->";

/**
 * Either marker, with the newlines after it. The newlines BEFORE it are trimmed
 * by hand in {@link stripMarker}: a leading `\n*` here made the strip quadratic
 * on a body of blank lines (100,000 newlines took 3.5 s), since every newline
 * started a scan to the end of the run.
 */
function makeStripRe(): RegExp {
  return new RegExp(
    `(?:${escapeRe(PUBLISH_MARKER_PREFIX)}\\s*batch=[^\\s]+\\s+draft=[^\\s]+\\s+hash=[^\\s]+\\s*-->|<!--${SOURCE_MARKER_BODY})\\n*`,
    "gi",
  );
}

function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

export function normalizeTitle(title: string): string {
  return title.trim().replace(/\s+/g, " ").toLowerCase();
}

export function computeDedupHash(targetOwner: string, targetRepo: string, title: string): string {
  const owner = targetOwner.trim().toLowerCase();
  const repo = targetRepo.trim().toLowerCase();
  const norm = normalizeTitle(title);
  return crypto.createHash("sha256").update(`${owner}/${repo}:${norm}`).digest("hex");
}

export function computeBodyHash(body: string): string {
  return crypto.createHash("sha256").update(body).digest("hex");
}

export interface PublishMarker {
  batchId: string;
  draftId: string;
  hash: string;
}

export function buildMarkerComment(marker: PublishMarker): string {
  return `${PUBLISH_MARKER_PREFIX} batch=${marker.batchId} draft=${marker.draftId} hash=${marker.hash} -->`;
}

export function injectMarker(body: string, marker: PublishMarker, source?: SourceMarker): string {
  // Replace existing marker comments if any are already present so re-publishes
  // do not accumulate stale lines.
  const stripped = stripMarker(body);
  const trimmed = stripped.replace(/\s+$/u, "");
  const sourceLine = source ? buildSourceMarkerComment(source) : null;
  return `${trimmed}\n\n${sourceLine ? `${sourceLine}\n` : ""}${buildMarkerComment(marker)}\n`;
}

/**
 * Strip ALL marker comments — global so an attacker-supplied requirement
 * body containing a fake marker cannot survive into the published issue
 * body and later be re-parsed as authoritative. Covers the publish marker and
 * the #1064 source marker alike, so the stripped text of a published issue is
 * the draft body it was published from (the reconcile sweep hashes it).
 */
export function stripMarker(body: string): string {
  let out = "";
  let last = 0;
  for (const m of body.matchAll(makeStripRe())) {
    let end = m.index;
    while (end > last && body.charCodeAt(end - 1) === 10) end -= 1;
    out += `${body.slice(last, end)}\n`;
    last = m.index + m[0].length;
  }
  return last === 0 ? body : out + body.slice(last);
}

export interface SourceMarker {
  projectId: string;
  analysisId?: string | null;
  requirementId?: string | null;
}

/**
 * The source marker line, or `null` when the project id is not a plain id.
 * Every value is checked against {@link SOURCE_ID_RE}, so nothing written here
 * can close the comment early or add markup to the issue body.
 */
export function buildSourceMarkerComment(source: SourceMarker): string | null {
  // `typeof` first: `RegExp.test` would stringify a missing id to "undefined".
  const isId = (v: unknown): v is string => typeof v === "string" && SOURCE_ID_RE.test(v);
  if (!isId(source.projectId)) return null;
  const parts = [`project=${source.projectId}`];
  if (isId(source.analysisId)) parts.push(`analysis=${source.analysisId}`);
  if (isId(source.requirementId)) parts.push(`requirement=${source.requirementId}`);
  return `${SOURCE_MARKER_PREFIX} ${parts.join(" ")} -->`;
}

/**
 * The source of an issue draft row: its project, the requirement it is linked
 * to, and the analysis its generator recorded in `metadata.analysisId`. A draft
 * METIS did not generate from an analysis (Deep Dive → Issue) names no analysis.
 */
export function sourceMarkerForDraft(draft: {
  projectId: string;
  requirementId: string | null;
  metadata: string | null;
}): SourceMarker {
  let analysisId: string | null = null;
  try {
    const meta = JSON.parse(draft.metadata ?? "{}") as { analysisId?: unknown } | null;
    if (meta && typeof meta.analysisId === "string") analysisId = meta.analysisId;
  } catch {
    /* unparseable metadata names no analysis */
  }
  return { projectId: draft.projectId, analysisId, requirementId: draft.requirementId };
}

/** What {@link parseSourceMarker} recovered from an issue body. */
export interface ParsedSourceMarker {
  /**
   * `marker` — the hidden comment; ids are complete. `legacy-footer` — the
   * visible footer of an issue published before #1064, whose project and
   * analysis ids are the first 8 characters only (the requirement id is whole).
   */
  form: "marker" | "legacy-footer";
  projectId: string;
  analysisId: string | null;
  requirementId: string | null;
}

/** The visible footer every draft carried before #1064. Bounded, so linear. */
const LEGACY_FOOTER_RE =
  /Generated by METIS · project=`([A-Za-z0-9_-]{1,64})` · analysis=`([A-Za-z0-9_-]{1,64})`(?: · requirement=`([A-Za-z0-9_-]{1,64})`)?/g;

/**
 * Read back where an issue came from: the hidden source marker, or the visible
 * footer of an issue published before #1064. Whichever sits LAST in the body
 * wins, because METIS writes its own after the requirement text. Like the
 * publish marker this is a hint, never an authority: issue bodies are editable
 * by anyone with write access, so check the ids against the database before
 * acting on them.
 */
export function parseSourceMarker(body: string | null | undefined): ParsedSourceMarker | null {
  if (!body) return null;
  let found: { at: number; value: ParsedSourceMarker } | null = null;
  for (const m of body.matchAll(new RegExp(`<!--${SOURCE_MARKER_BODY}`, "gi"))) {
    const fields = new Map<string, string>();
    for (const token of m[1]!.trim().split(/[ \t]+/)) {
      const eq = token.indexOf("=");
      if (eq > 0 && SOURCE_ID_RE.test(token.slice(eq + 1))) {
        fields.set(token.slice(0, eq), token.slice(eq + 1));
      }
    }
    const projectId = fields.get("project");
    if (!projectId) continue;
    found = {
      at: m.index,
      value: {
        form: "marker",
        projectId,
        analysisId: fields.get("analysis") ?? null,
        requirementId: fields.get("requirement") ?? null,
      },
    };
  }
  for (const m of body.matchAll(LEGACY_FOOTER_RE)) {
    if (found && found.at > m.index) continue;
    found = {
      at: m.index,
      value: {
        form: "legacy-footer",
        projectId: m[1]!,
        analysisId: m[2]!,
        requirementId: m[3] ?? null,
      },
    };
  }
  return found?.value ?? null;
}

export function parseMarker(body: string | null | undefined): PublishMarker | null {
  if (!body) return null;
  const m = MARKER_RE.exec(body);
  if (!m) return null;
  return { batchId: m[1], draftId: m[2], hash: m[3] };
}
