/**
 * #1276 — what a draft's body becomes on the published issue: the parent
 * epic's number and link when the epic was published in an earlier batch, and
 * one plain sentence in place of the internal `unverified` label.
 */
import { describe, expect, it } from "vitest";
import {
  UNVERIFIED_PUBLISHED_NOTE,
  withParentEpicLink,
  withUnverifiedNote,
  withoutParentEpicLink,
  withoutUnverifiedNote,
} from "./published-body.js";

const BODY = [
  "> Parent epic: **[Epic] Apollo — 3 requirements**",
  "",
  "## Description",
  "",
  "Do the thing.",
  "",
  "## Acceptance criteria",
  "",
  "- [ ] It works",
  "",
  "---",
  "> Generated by METIS",
].join("\n");

const EPIC = { issueNumber: 12, htmlUrl: "https://github.com/acme/metis/issues/12" };

describe("withParentEpicLink", () => {
  it("adds the epic's number and link to the generated parent line", () => {
    const out = withParentEpicLink(BODY, EPIC);
    expect(out.split("\n")[0]).toBe(
      "> Parent epic: **[Epic] Apollo — 3 requirements** ([#12](https://github.com/acme/metis/issues/12))",
    );
    expect(out.split("\n").slice(1)).toEqual(BODY.split("\n").slice(1));
  });

  it("is idempotent: a line that already names a number is left alone", () => {
    const once = withParentEpicLink(BODY, EPIC);
    expect(withParentEpicLink(once, { ...EPIC, issueNumber: 99 })).toBe(once);
  });

  it("writes a bare #N when the recorded URL is not an https URL", () => {
    for (const htmlUrl of [
      "",
      "javascript:alert(1)",
      "http://github.com/a/b/issues/12",
      "https://x/y z",
    ]) {
      expect(withParentEpicLink(BODY, { issueNumber: 12, htmlUrl }).split("\n")[0]).toBe(
        "> Parent epic: **[Epic] Apollo — 3 requirements** (#12)",
      );
    }
  });

  it("leaves a body whose first line is not the generated parent line unchanged", () => {
    const edited = `Intro\n${BODY}`;
    expect(withParentEpicLink(edited, EPIC)).toBe(edited);
    expect(withParentEpicLink("", EPIC)).toBe("");
  });

  it("refuses a non-positive issue number", () => {
    expect(withParentEpicLink(BODY, { ...EPIC, issueNumber: 0 })).toBe(BODY);
  });
});

describe("withoutParentEpicLink", () => {
  it("undoes withParentEpicLink, so drift detection compares the draft's own text", () => {
    expect(withoutParentEpicLink(withParentEpicLink(BODY, EPIC))).toBe(BODY);
    expect(withoutParentEpicLink(withParentEpicLink(BODY, { ...EPIC, htmlUrl: "" }))).toBe(BODY);
    expect(withoutParentEpicLink(BODY)).toBe(BODY);
  });
});

describe("withUnverifiedNote", () => {
  it("puts the sentence above the acceptance criteria when the draft carries `unverified`", () => {
    const out = withUnverifiedNote(BODY, ["feature", "Unverified"]);
    const lines = out.split("\n");
    const at = lines.indexOf("## Acceptance criteria");
    expect(lines[at - 2]).toBe(UNVERIFIED_PUBLISHED_NOTE);
    expect(lines[at - 1]).toBe("");
    expect(out.split(UNVERIFIED_PUBLISHED_NOTE)).toHaveLength(2);
  });

  it("is one plain sentence that never says `unverified`", () => {
    expect(UNVERIFIED_PUBLISHED_NOTE).toBe(
      "METIS could not confirm the code references behind this item; check them before relying on them.",
    );
    expect(UNVERIFIED_PUBLISHED_NOTE.toLowerCase()).not.toContain("unverified");
  });

  it("changes nothing for a draft without the label", () => {
    expect(withUnverifiedNote(BODY, ["feature", "unverified-claims"])).toBe(BODY);
  });

  it("is idempotent", () => {
    const once = withUnverifiedNote(BODY, ["unverified"]);
    expect(withUnverifiedNote(once, ["unverified"])).toBe(once);
  });

  it("appends the sentence to a body with no acceptance criteria heading", () => {
    expect(withUnverifiedNote("Just text\n", ["unverified"])).toBe(
      `Just text\n\n${UNVERIFIED_PUBLISHED_NOTE}`,
    );
  });
});

describe("withoutUnverifiedNote", () => {
  it("undoes withUnverifiedNote wherever it was placed", () => {
    expect(withoutUnverifiedNote(withUnverifiedNote(BODY, ["unverified"]))).toBe(BODY);
    expect(withoutUnverifiedNote(withUnverifiedNote("Just text", ["unverified"]))).toBe(
      "Just text",
    );
    expect(withoutUnverifiedNote(BODY)).toBe(BODY);
  });
});
