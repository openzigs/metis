/**
 * #1230 — approving or editing a requirement makes a reader-layout BRD that
 * lists the project's approved requirements (#1218) out of date.
 *
 * Nothing new decides that: such a document's input snapshot covers its
 * approved requirements (`generation-inputs.ts`), so this only asks the
 * existing auto-update check (`checkIncrementalRegeneration`) to look again,
 * limited to the documents that read them. Unchanged inputs queue nothing; an
 * auto-update document whose inputs moved gets one regeneration task, which
 * reuses every section whose own inputs are unchanged (#857). A document
 * without auto-update is regenerated by hand as before, and its next run sees
 * the changed inputs.
 *
 * Best effort and off the request path: the requirement write has already
 * committed, and a failed check is logged, never thrown, since the next
 * ingest's check (or a manual regenerate) reads the same snapshot. Checks for
 * one project are coalesced, so approving fifty requirements in a row runs at
 * most one check at a time and one more after it, not fifty.
 */
import { prisma } from "../prisma.js";
import { createChildLogger } from "../logger.js";
import { readBrdLayoutSetting } from "./brd-layout.js";

const log = createChildLogger("docs-gen-approved-requirements-staleness");

interface ProjectCheck {
  /** Another change arrived while this check ran: check once more after it. */
  again: boolean;
  /**
   * #1246 — the next check may be limited to repository- or path-scoped
   * documents: every change waiting for it was a code-link write. One
   * requirement change among them widens it to every reader BRD.
   */
  nextScopedOnly: boolean;
  done: Promise<void>;
}

const running = new Map<string, ProjectCheck>();

// Loaded on first use: the check pulls in the whole generation pipeline, which
// the routes and services calling this should not load at startup.
let incremental: Promise<typeof import("./incremental.js")> | undefined;

function checkProject(projectId: string, scopedOnly = false): Promise<void> {
  const current = running.get(projectId);
  if (current) {
    current.nextScopedOnly = current.again ? current.nextScopedOnly && scopedOnly : scopedOnly;
    current.again = true;
    return current.done;
  }
  const check: ProjectCheck = { again: false, nextScopedOnly: scopedOnly, done: Promise.resolve() };
  check.done = (async () => {
    try {
      // A failed import is not cached: the next change tries again.
      incremental ??= import("./incremental.js").catch((err: unknown) => {
        incremental = undefined;
        throw err;
      });
      const { checkIncrementalRegeneration } = await incremental;
      do {
        const scoped = check.nextScopedOnly;
        check.again = false;
        check.nextScopedOnly = true;
        await checkIncrementalRegeneration(projectId, undefined, {
          approvedRequirementsOnly: true,
          ...(scoped ? { scopedApprovedRequirementsOnly: true } : {}),
        });
      } while (check.again);
    } catch (err) {
      log.warn("Could not check reader BRDs after a requirement change", {
        projectId,
        error: (err as Error).message,
      });
    } finally {
      running.delete(projectId);
    }
  })();
  running.set(projectId, check);
  return check.done;
}

/**
 * Call after a committed write that changed `projectId`'s requirements without
 * naming them: requirements promoted from an analysis's approvals, a new set
 * that may also move the run the Requirements hub opens on. Resolves when the
 * check is done; never rejects.
 */
export async function noteProjectRequirementsChanged(projectId: string): Promise<void> {
  try {
    // Under the catalogue layout no BRD lists approved requirements.
    if (readBrdLayoutSetting().layout !== "reader") return;
    await checkProject(projectId);
  } catch (err) {
    log.warn("Could not check reader BRDs after a requirement change", {
      projectId,
      error: (err as Error).message,
    });
  }
}

/**
 * Call after a committed write that may have approved, un-approved or edited
 * `requirementIds`. Resolves when the check is done; never rejects, so callers
 * may leave it unawaited (`void noteRequirementsChanged(...)`).
 */
export async function noteRequirementsChanged(requirementIds: readonly string[]): Promise<void> {
  await noteChanged(requirementIds, false);
}

/**
 * #1246 — call after a committed write that added code links (a mapping, or a
 * merged pull request's files) to `requirementIds`. A code link changes only
 * which approved requirements a repository- or path-scoped reader BRD lists,
 * never what an unscoped one hashes, so only the scoped documents are checked.
 * Resolves when the check is done; never rejects.
 */
export async function noteRequirementCodeLinksChanged(
  requirementIds: readonly string[],
): Promise<void> {
  await noteChanged(requirementIds, true);
}

async function noteChanged(requirementIds: readonly string[], scopedOnly: boolean): Promise<void> {
  try {
    if (requirementIds.length === 0) return;
    // Under the catalogue layout no BRD lists approved requirements.
    if (readBrdLayoutSetting().layout !== "reader") return;
    const rows = await prisma.requirement.findMany({
      where: { id: { in: [...new Set(requirementIds)] } },
      select: { projectId: true },
    });
    await Promise.all(
      [...new Set(rows.map((r) => r.projectId))].map((projectId) =>
        checkProject(projectId, scopedOnly),
      ),
    );
  } catch (err) {
    log.warn("Could not check reader BRDs after a requirement change", {
      error: (err as Error).message,
    });
  }
}
