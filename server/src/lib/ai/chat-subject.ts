/**
 * Issue #2350 (epic #2328) — what an "Ask about this" link names, for the
 * caller only.
 *
 * Chat opened from a project, a change request or a requirement is scoped to
 * the project that holds the item. The chat page learns which project, and the
 * item's name, from here, so this is where reading the item is authorized: the
 * same rule as the item's own page.
 *
 *   - a project: the caller reaches the live project (`assertLiveProjectAccess`);
 *   - a change request or a requirement: the caller also holds `analysis.read`
 *     (the change request page's permission), the item is not deleted, and the
 *     caller reaches the project that holds it.
 *
 * An unknown id, a deleted item, and an item in a project the caller cannot
 * reach all answer the one 404, so a probe cannot tell them apart. A role
 * without `analysis.read` is refused 403, as the change request page refuses it.
 */
import {
  hasPermission,
  type AuthPayload,
  type ChatSubjectDto,
  type ChatSubjectKind,
} from "@metis/shared";
import { prisma } from "../prisma.js";
import { AppError } from "../../middleware/error-handler.js";
import { assertLiveProjectAccess } from "../custom-agents/authz.js";
import { changeRequestDetails } from "../analysis/change-request.js";

function subjectNotFound(): AppError {
  return new AppError(404, "NOT_FOUND", "Not found");
}

/** Run `check`, answering the subject's one 404 for any project-access 404. */
async function asSubject404(check: () => Promise<void>): Promise<void> {
  try {
    await check();
  } catch (err) {
    if (err instanceof AppError && err.statusCode === 404) throw subjectNotFound();
    throw err;
  }
}

async function liveProjectName(projectId: string): Promise<string> {
  const project = await prisma.project.findFirst({
    where: { id: projectId, deletedAt: null },
    select: { name: true },
  });
  if (!project) throw subjectNotFound();
  return project.name;
}

async function changeRequestTitle(projectId: string, analysisId: string): Promise<string | null> {
  const run = await prisma.analysis.findFirst({
    where: { id: analysisId, projectId, deletedAt: null },
    select: { id: true, title: true, titleGenerated: true, metadata: true, startedAt: true },
  });
  if (!run) return null;
  // The change request's own read path: a title not yet backfilled is
  // generated by the same rule its page uses.
  const details = await changeRequestDetails(projectId, [run]);
  return details.get(run.id)?.title ?? null;
}

/**
 * The item `kind`/`id` as the caller may see it.
 *
 * @throws AppError 404 — unknown or deleted item, or the caller cannot reach its project
 * @throws AppError 403 — a change request or requirement, and the caller lacks `analysis.read`
 */
export async function resolveChatSubject(
  user: AuthPayload,
  kind: ChatSubjectKind,
  id: string,
): Promise<ChatSubjectDto> {
  if (kind === "project") {
    await asSubject404(() => assertLiveProjectAccess(user, id));
    const name = await liveProjectName(id);
    return {
      kind,
      id,
      projectId: id,
      projectName: name,
      title: name,
      changeRequestTitle: null,
    };
  }

  if (!hasPermission(user.role, "analysis.read")) {
    throw new AppError(403, "FORBIDDEN", "Requires permission analysis.read");
  }

  if (kind === "change-request") {
    const run = await prisma.analysis.findFirst({
      where: { id, deletedAt: null },
      select: { projectId: true },
    });
    if (!run) throw subjectNotFound();
    await asSubject404(() => assertLiveProjectAccess(user, run.projectId));
    const projectName = await liveProjectName(run.projectId);
    const title = await changeRequestTitle(run.projectId, id);
    if (title === null) throw subjectNotFound();
    return {
      kind,
      id,
      projectId: run.projectId,
      projectName,
      title,
      changeRequestTitle: null,
    };
  }

  const requirement = await prisma.requirement.findFirst({
    where: { id, deletedAt: null },
    select: { projectId: true, analysisId: true, title: true },
  });
  if (!requirement) throw subjectNotFound();
  await asSubject404(() => assertLiveProjectAccess(user, requirement.projectId));
  const projectName = await liveProjectName(requirement.projectId);
  // Scoped on the requirement's own project, so a mismatched run is never read.
  const crTitle = await changeRequestTitle(requirement.projectId, requirement.analysisId);
  // A requirement of a deleted change request is gone with it.
  if (crTitle === null) throw subjectNotFound();
  return {
    kind,
    id,
    projectId: requirement.projectId,
    projectName,
    title: requirement.title,
    changeRequestTitle: crTitle,
  };
}
