/**
 * #1064 — the internal ids moved out of the visible draft footer into a hidden
 * source marker written when an issue is published. An issue published before
 * that still carries the visible footer, and both must read back the same way.
 */
import { describe, expect, it } from "vitest";
import {
  buildSourceMarkerComment,
  computeBodyHash,
  injectMarker,
  parseMarker,
  parseSourceMarker,
  sourceMarkerForDraft,
  stripMarker,
} from "../src/lib/publishing/dedup.js";
import { expectLinearTime } from "./helpers/linear-time.js";

const PUBLISH = { batchId: "b1", draftId: "d1", hash: "h1" };
const SOURCE = {
  projectId: "cmv2x496000001",
  analysisId: "cmv2xnnw000002",
  requirementId: "cmv2y5bgj1ut2jm9",
};

/** The footer line every feature draft carried before #1064. */
function legacyFooter(project: string, analysis: string, requirement?: string): string {
  return (
    `> Generated by METIS · project=\`${project}\` · analysis=\`${analysis}\`` +
    (requirement ? ` · requirement=\`${requirement}\`` : "")
  );
}

describe("source marker (#1064)", () => {
  it("writes the ids as one HTML comment line", () => {
    expect(buildSourceMarkerComment(SOURCE)).toBe(
      "<!-- metis-source: project=cmv2x496000001 analysis=cmv2xnnw000002 requirement=cmv2y5bgj1ut2jm9 -->",
    );
  });

  it("leaves out an absent analysis or requirement (the epic has no requirement)", () => {
    expect(buildSourceMarkerComment({ projectId: "p1", analysisId: "a1" })).toBe(
      "<!-- metis-source: project=p1 analysis=a1 -->",
    );
    expect(buildSourceMarkerComment({ projectId: "p1", requirementId: null })).toBe(
      "<!-- metis-source: project=p1 -->",
    );
  });

  it("never writes a value that could close the comment or add markup", () => {
    expect(buildSourceMarkerComment({ projectId: "p1 --> <script>" })).toBeNull();
    expect(
      buildSourceMarkerComment({
        projectId: "p1",
        analysisId: "a1 -->",
        requirementId: "<img src=x>",
      }),
    ).toBe("<!-- metis-source: project=p1 -->");
    expect(buildSourceMarkerComment({ projectId: "x".repeat(65) })).toBeNull();
  });

  it("is injected above the publish marker, and both read back", () => {
    const stamped = injectMarker("Body text", PUBLISH, SOURCE);
    expect(stamped).toBe(
      `Body text\n\n${buildSourceMarkerComment(SOURCE)}\n<!-- metis-publish: batch=b1 draft=d1 hash=h1 -->\n`,
    );
    expect(parseMarker(stamped)).toEqual(PUBLISH);
    expect(parseSourceMarker(stamped)).toEqual({ form: "marker", ...SOURCE });
  });

  it("without a source, injectMarker writes exactly what it wrote before #1064", () => {
    expect(injectMarker("Body text", PUBLISH)).toBe(
      "Body text\n\n<!-- metis-publish: batch=b1 draft=d1 hash=h1 -->\n",
    );
  });

  it("re-publishing replaces both markers instead of stacking them", () => {
    const once = injectMarker("Body text", PUBLISH, SOURCE);
    const twice = injectMarker(once, { ...PUBLISH, batchId: "b2" }, SOURCE);
    expect(twice.match(/metis-source:/g)).toHaveLength(1);
    expect(twice.match(/metis-publish:/g)).toHaveLength(1);
    expect(parseMarker(twice)?.batchId).toBe("b2");
  });

  it("strips both markers, so a published body hashes back to its draft body", () => {
    // The reconcile sweep hashes `stripMarker(issue.body).trimEnd()` and
    // compares it with the hash of the draft body.
    const draftBody = "## Description\n\nText\n\n---\n> Generated by METIS";
    const published = injectMarker(draftBody, PUBLISH, SOURCE);
    expect(computeBodyHash(stripMarker(published).trimEnd())).toBe(computeBodyHash(draftBody));
  });

  it("an issue published before #1064 strips and hashes exactly as it did", () => {
    const oldDraftBody = `## Description\n\nText\n\n---\n${legacyFooter("cmv2x496", "cmv2xnnw", "cmv2y5bgj1ut2jm9")}`;
    const oldPublished = `${oldDraftBody}\n\n<!-- metis-publish: batch=b1 draft=d1 hash=h1 -->\n`;
    expect(injectMarker(oldDraftBody, PUBLISH)).toBe(oldPublished);
    expect(stripMarker(oldPublished).trimEnd()).toBe(oldDraftBody);
    expect(parseMarker(oldPublished)).toEqual(PUBLISH);
  });

  it("strips the same text the old newline-greedy pattern did", () => {
    const marker = "<!-- metis-publish: batch=b draft=d hash=h -->";
    for (const body of [
      `a\n\n\n${marker}\n\n\nb`,
      `${marker}\nb`,
      `a\n${marker}`,
      `a ${marker} b`,
      `a\n\n${marker}\n\n${marker}\n\nb`,
    ]) {
      const old = body.replace(
        /\n*<!-- metis-publish:\s*batch=[^\s]+\s+draft=[^\s]+\s+hash=[^\s]+\s*-->\n*/gi,
        "\n",
      );
      expect(stripMarker(body)).toBe(old);
    }
  });

  it("removes a forged source marker from requirement text before publishing", () => {
    const body = "Real text\n<!-- metis-source: project=evil requirement=other -->\nMore";
    const stamped = injectMarker(body, PUBLISH, SOURCE);
    expect(stamped).not.toContain("project=evil");
    expect(parseSourceMarker(stamped)).toEqual({ form: "marker", ...SOURCE });
  });
});

describe("sourceMarkerForDraft (#1064)", () => {
  it("reads the project and requirement from the row and the analysis from its metadata", () => {
    expect(
      sourceMarkerForDraft({
        projectId: "p1",
        requirementId: "r1",
        metadata: JSON.stringify({ analysisId: "a1", requirementKey: "k" }),
      }),
    ).toEqual({ projectId: "p1", analysisId: "a1", requirementId: "r1" });
  });

  it("names no analysis for a draft that records none, or whose metadata is unreadable", () => {
    for (const metadata of [null, "{not json", "null", "[]", JSON.stringify({ analysisId: 7 })]) {
      expect(sourceMarkerForDraft({ projectId: "p1", requirementId: null, metadata })).toEqual({
        projectId: "p1",
        analysisId: null,
        requirementId: null,
      });
    }
  });

  it("writes no marker for a row with no usable project id", () => {
    const row = { requirementId: "r1", metadata: null } as unknown as Parameters<
      typeof sourceMarkerForDraft
    >[0];
    expect(buildSourceMarkerComment(sourceMarkerForDraft(row))).toBeNull();
  });
});

describe("parseSourceMarker — old and new issues (#1064)", () => {
  it("reads the visible footer of an issue published before #1064", () => {
    const body = `Text\n\n---\n${legacyFooter("cmv2x496", "cmv2xnnw", "cmv2y5bgj1ut2jm9")}\n\n<!-- metis-publish: batch=b1 draft=d1 hash=h1 -->\n`;
    expect(parseSourceMarker(body)).toEqual({
      form: "legacy-footer",
      projectId: "cmv2x496",
      analysisId: "cmv2xnnw",
      requirementId: "cmv2y5bgj1ut2jm9",
    });
  });

  it("reads an old epic footer, which names no requirement", () => {
    expect(parseSourceMarker(legacyFooter("cmv2x496", "cmv2xnnw"))).toEqual({
      form: "legacy-footer",
      projectId: "cmv2x496",
      analysisId: "cmv2xnnw",
      requirementId: null,
    });
  });

  it("takes whichever METIS wrote last when a body carries both", () => {
    // A draft whose text a reviewer edited keeps its old visible footer and
    // still gets the marker when it is published.
    const body = injectMarker(
      `Text\n${legacyFooter("oldproj1", "oldanal1", "oldreq")}`,
      PUBLISH,
      SOURCE,
    );
    expect(parseSourceMarker(body)).toEqual({ form: "marker", ...SOURCE });
    // A footer pasted into requirement text does not outrank the real footer.
    const forged = `${legacyFooter("evil0000", "evil0000", "evil")}\nText\n${legacyFooter("cmv2x496", "cmv2xnnw", "real")}`;
    expect(parseSourceMarker(forged)?.requirementId).toBe("real");
  });

  it("returns null when the body names no source", () => {
    expect(parseSourceMarker(null)).toBeNull();
    expect(parseSourceMarker("")).toBeNull();
    expect(parseSourceMarker("> Generated by METIS")).toBeNull();
    expect(parseSourceMarker("<!-- metis-source: analysis=a1 -->")).toBeNull();
    expect(parseSourceMarker("<!-- metis-source: project=<b> -->")).toBeNull();
  });
});

describe("marker regexes are linear in the body (#1064)", () => {
  const floods: Array<[string, (n: number) => string]> = [
    ["blank lines", (n) => "\n".repeat(n)],
    ["source-marker prefixes", (n) => "<!-- metis-source: ".repeat(Math.ceil(n / 19))],
    ["publish-marker prefixes", (n) => "<!-- metis-publish: batch=".repeat(Math.ceil(n / 26))],
    ["one unterminated marker", (n) => `<!-- metis-source: ${"a".repeat(n)}`],
    ["footer prefixes", (n) => "Generated by METIS · project=`".repeat(Math.ceil(n / 30))],
  ];
  for (const [label, build] of floods) {
    it(`stripMarker and parseSourceMarker on ${label}`, () => {
      expectLinearTime(`strip ${label}`, (n) => {
        const body = build(n);
        return () => stripMarker(body);
      });
      expectLinearTime(`parse ${label}`, (n) => {
        const body = build(n);
        return () => parseSourceMarker(body);
      });
    });
  }
});
