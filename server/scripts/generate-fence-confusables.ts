/**
 * #1114 — regenerate the confusables table behind the fence scrub
 * (`server/src/lib/ai/tool-runtime/fence-scrub.ts`).
 *
 * Two inputs, two outputs:
 *
 *   1. Unicode `confusables.txt` (UTS #39) → the committed SUBSET
 *      `server/scripts/data/fence-confusables-subset.txt`: every line whose source is
 *      one code point and whose prototype is one character a fence is built from
 *      (`=`, `-`, `_`, the letters of METIS DATA BOUNDARY in either case, and `l`,
 *      the prototype of `I`; since #1351 also `<`, `>` and `Q`, for the
 *      `<<<END REQUIREMENT>>>` fence). Comments are dropped, so the subset is pure ASCII.
 *      The header records the source URL, its `Date:`/`Version:` lines and the
 *      SHA-256 of the full file.
 *   2. The subset → `server/src/lib/ai/tool-runtime/fence-confusables.generated.ts`.
 *
 * The test `server/tests/lib/ai/fence-confusables-generated.test.ts` re-renders (2)
 * from the committed subset and requires it to equal the committed module, so the
 * table cannot drift from its source and needs no network.
 *
 * Usage (from `server/`):
 *   curl -sO https://www.unicode.org/Public/security/latest/confusables.txt
 *   npx tsx scripts/generate-fence-confusables.ts --from confusables.txt
 *   npx tsx scripts/generate-fence-confusables.ts          # module only, from the subset
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const SOURCE_URL = "https://www.unicode.org/Public/security/latest/confusables.txt";

/** Prototype character → the character the scrub's comparison copy uses. */
const FOLD_TARGET: Readonly<Record<string, string>> = (() => {
  const out: Record<string, string> = { "=": "=", "-": "-", _: "_", l: "I", "<": "<", ">": ">" };
  for (const c of "ABDEIMNOQRSTUY") {
    out[c] = c;
    out[c.toLowerCase()] = c;
  }
  return out;
})();

const LINE = /^([0-9A-F]{4,6}) ;\s+([0-9A-F]{4,6}) ;\s+(MA)\b/;

/** Step 1: the full `confusables.txt` → the committed subset text. */
export function extractSubset(full: string): string {
  const sha = createHash("sha256").update(full, "utf8").digest("hex");
  const meta = full
    .split("\n")
    .filter((l) => /^# (Date|Version):/.test(l))
    .map((l) => l.trim());
  const rows: string[] = [];
  for (const line of full.split("\n")) {
    const m = LINE.exec(line);
    if (!m) continue;
    const target = String.fromCodePoint(parseInt(m[2], 16));
    if (FOLD_TARGET[target] === undefined) continue;
    rows.push(`${m[1]} ; ${m[2]} ; ${m[3]}`);
  }
  return [
    "# Subset of Unicode confusables.txt for the #1114 fence scrub.",
    `# Source: ${SOURCE_URL}`,
    ...meta,
    `# SHA-256 of the full file: ${sha}`,
    "# Rows: single-code-point source ; single prototype in = - _ < > l A B D E I M N O Q R S T U Y (either case) ; type",
    "# Regenerate with server/scripts/generate-fence-confusables.ts --from <confusables.txt>.",
    ...rows,
    "",
  ].join("\n");
}

/** Step 2: the subset → `[target, sources[]]` pairs, targets sorted, sources ascending. */
export function parseSubset(subset: string): Array<[string, number[]]> {
  const byTarget = new Map<string, number[]>();
  for (const line of subset.split("\n")) {
    if (line.startsWith("#") || line.trim() === "") continue;
    const m = LINE.exec(line);
    if (!m) throw new Error(`fence-confusables subset: unparsable row ${JSON.stringify(line)}`);
    const to = FOLD_TARGET[String.fromCodePoint(parseInt(m[2], 16))];
    if (to === undefined)
      throw new Error(`fence-confusables subset: unexpected prototype in ${line}`);
    const list = byTarget.get(to) ?? [];
    list.push(parseInt(m[1], 16));
    byTarget.set(to, list);
  }
  return [...byTarget.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([to, from]) => [to, [...new Set(from)].sort((x, y) => x - y)]);
}

const hex = (n: number) => `0x${n.toString(16).toUpperCase().padStart(4, "0")}`;

/** Step 2: render the TypeScript module. */
export function renderModule(subset: string): string {
  const header = subset
    .split("\n")
    .filter((l) => /^# (Source|Date|Version|SHA-256)/.test(l))
    .map((l) => ` * ${l.slice(2)}`);
  const rows = parseSubset(subset).map(
    ([to, from]) => `  [${JSON.stringify(to)}, [${from.map(hex).join(", ")}]],`,
  );
  return [
    "/**",
    " * GENERATED by server/scripts/generate-fence-confusables.ts from",
    " * server/scripts/data/fence-confusables-subset.txt. Do not edit by hand.",
    " *",
    ...header,
    " *",
    " * Each row: the character the fence scrub's comparison copy uses, and every",
    " * code point whose Unicode confusables prototype is that character.",
    " */",
    "// prettier-ignore",
    "export const CONFUSABLE_SOURCES: ReadonlyArray<readonly [string, readonly number[]]> = [",
    ...rows,
    "];",
    "",
  ].join("\n");
}

const here = dirname(fileURLToPath(import.meta.url));
export const SUBSET_PATH = resolve(here, "data/fence-confusables-subset.txt");
export const MODULE_PATH = resolve(
  here,
  "../src/lib/ai/tool-runtime/fence-confusables.generated.ts",
);

function main(argv: string[]): void {
  const fromIdx = argv.indexOf("--from");
  if (fromIdx >= 0) {
    const src = argv[fromIdx + 1];
    if (!src) throw new Error("--from needs a path to confusables.txt");
    writeFileSync(SUBSET_PATH, extractSubset(readFileSync(src, "utf8")));
  }
  writeFileSync(MODULE_PATH, renderModule(readFileSync(SUBSET_PATH, "utf8")));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}
