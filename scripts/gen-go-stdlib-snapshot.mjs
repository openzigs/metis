#!/usr/bin/env node
/**
 * Regenerate what the Go type resolver knows about the standard library (#1071).
 *
 *   node scripts/gen-go-stdlib-snapshot.mjs
 *
 * Needs a Go toolchain on PATH — the Go release whose standard library the
 * resolver should describe. Run it when moving to a new Go release; nothing in
 * the build, the tests or CI runs Go.
 *
 * It runs `scripts/go-stdlib-snapshot/main.go` (standard library only) and
 * writes two files, which a test keeps in step
 * (`server/tests/lib/code-graph/go-stdlib-snapshot.test.ts`):
 *
 *   - `server/src/lib/code-graph/go-stdlib.snapshot.json` — the raw facts:
 *     `go list std`, every exported interface type, and the members of concrete
 *     types that are typed as one;
 *   - `server/src/lib/code-graph/go-stdlib.data.ts` — the same facts as the
 *     constants `go-stdlib.ts` reads. GENERATED: edit neither by hand.
 *
 * No user input reaches a command: both are fixed argument vectors, no shell.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generator = path.join(repoRoot, "scripts", "go-stdlib-snapshot", "main.go");
const outDir = path.join(repoRoot, "server", "src", "lib", "code-graph");
const snapshotPath = path.join(outDir, "go-stdlib.snapshot.json");
const dataPath = path.join(outDir, "go-stdlib.data.ts");

/**
 * The TypeScript the resolver imports, from a parsed snapshot.
 *
 * @param {{ goVersion: string, packages: string[], interfaces: Record<string, string[]>,
 *   interfaceMembers: Record<string, string[]>, interfaceVars: Record<string, string[]>,
 *   funcVars: Record<string, string[]> }} snap
 */
function renderData(snap) {
  const table = (record) =>
    Object.keys(record)
      .sort()
      .map((key) => `  [${JSON.stringify(key)}, ${JSON.stringify(record[key].join(" "))}],`)
      .join("\n");
  return [
    "/**",
    " * GENERATED by `scripts/gen-go-stdlib-snapshot.mjs` from the Go toolchain — do not edit.",
    " * The same facts as `go-stdlib.snapshot.json`; `go-stdlib.ts` explains what they are for.",
    " */",
    "",
    "/** The Go release these lists describe (`runtime.Version()`). */",
    `export const GO_STDLIB_SNAPSHOT_VERSION = ${JSON.stringify(snap.goVersion)};`,
    "",
    "/** `go list std`, public packages only, merged over the platforms the generator lists. */",
    "export const GO_STDLIB_PACKAGE_LIST: readonly string[] = [",
    ...snap.packages.map((p) => `  ${JSON.stringify(p)},`),
    "];",
    "",
    "/** Import path → every exported interface type it declares, space-separated. */",
    "export const GO_STDLIB_INTERFACE_TYPES: ReadonlyArray<readonly [string, string]> = [",
    table(snap.interfaces),
    "];",
    "",
    "/**",
    " * `importPath.Type` → the members of that concrete type typed as an exported",
    " * standard-library interface: a field by name, a method as `Name(i,j)` with the",
    " * positions of the results that are one. A `*` after the name marks a method the",
    " * type PROMOTES from an embedded interface (`ReadAt*`): dispatched at run time.",
    " */",
    "export const GO_STDLIB_INTERFACE_MEMBERS: ReadonlyArray<readonly [string, string]> = [",
    table(snap.interfaceMembers),
    "];",
    "",
    "/** Import path → exported package-level variables typed as such an interface. */",
    "export const GO_STDLIB_INTERFACE_VARS: ReadonlyArray<readonly [string, string]> = [",
    table(snap.interfaceVars),
    "];",
    "",
    "/** Import path → exported package-level variables of a func type (`flag.Usage`). */",
    "export const GO_STDLIB_FUNC_VARS: ReadonlyArray<readonly [string, string]> = [",
    table(snap.funcVars),
    "];",
    "",
  ].join("\n");
}

const raw = execFileSync("go", ["run", generator], {
  cwd: repoRoot,
  env: { ...process.env, CGO_ENABLED: "0" },
  encoding: "utf8",
  maxBuffer: 64 * 1024 * 1024,
});
const snap = JSON.parse(raw);
fs.writeFileSync(snapshotPath, `${JSON.stringify(snap, null, 2)}\n`);
fs.writeFileSync(dataPath, renderData(snap));
execFileSync("pnpm", ["exec", "prettier", "--write", snapshotPath, dataPath], {
  cwd: repoRoot,
  stdio: "inherit",
});
console.log(
  `${snap.goVersion}: ${snap.packages.length} packages, ` +
    `${Object.values(snap.interfaces).flat().length} interface types, ` +
    `${Object.values(snap.interfaceMembers).flat().length} interface-typed members ` +
    `(not type-checked on this host: ${snap.unchecked.join(", ") || "none"})`,
);
